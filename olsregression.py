import pandas as pd
from sklearn.model_selection import train_test_split, StratifiedKFold, cross_val_score
from sklearn.metrics import classification_report, confusion_matrix, roc_auc_score, accuracy_score
from xgboost import XGBClassifier

# 1. Dataset Load Karein
file_path = '/content/drive/MyDrive/Data/master_landslide_dataset_shuffled.csv'
df = pd.read_csv(file_path).dropna()

feature_cols = [
    'DEM_Elevation',
    'DEM_Slope_Deg',
    'DEM_Aspect_Deg',
    'DEM_Curvature',
    'DEM_TWI',
    'IMD_Rainfall_3D'
]

X = df[feature_cols]
y = df['Landslide']

# 2. Same Train-Test Split (seed 42 taaki RF se direct compare ho sake)
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42, stratify=y
)

# 3. XGBoost Model
xgb_model = XGBClassifier(
    n_estimators=250,
    max_depth=6,
    learning_rate=0.04,
    subsample=0.8,
    colsample_bytree=0.8,
    gamma=1.0,
    random_state=42,
    eval_metric='logloss',
    n_jobs=-1
)

