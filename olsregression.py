import matplotlib.pyplot as plt
import statsmodels.api as sm
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from xgboost import XGBClassifier

file_path = '/content/drive/MyDrive/Data/master_landslide_dataset_shuffled.csv'
df = pd.read_csv(file_path).dropna()

feature_cols = [
    'DEM_Elevation',
    'DEM_Slope_Deg',
    'DEM_Aspect_Deg',
    'DEM_Curvature',
    'DEM_TWI',
    'IMD_Rainfall_3D'
]

X = df[feature_cols]
y = df['Landslide']

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42, stratify=y
)

# -------------------------------------------------------------
# 2. Model 1: OLS Regression (Absolute t-statistic Preference)
# -------------------------------------------------------------
# Statistical weight dekhne ke liye absolute t-value use hoti hai
X_ols = sm.add_constant(df[feature_cols])
ols_res = sm.OLS(y, X_ols).fit()
ols_t_vals = ols_res.tvalues.drop('const').abs()
ols_pct = (ols_t_vals / ols_t_vals.sum()) * 100

# -------------------------------------------------------------
# 3. Model 2: Random Forest (MDI / Gini Importance)
# -------------------------------------------------------------
rf = RandomForestClassifier(n_estimators=200, max_depth=12, random_state=42, n_jobs=-1)
rf.fit(X_train, y_train)
rf_pct = pd.Series(rf.feature_importances_ * 100, index=feature_cols)

# -------------------------------------------------------------
# 4. Model 3: XGBoost (Gain-based Importance)
# -------------------------------------------------------------
xgb = XGBClassifier(n_estimators=250, max_depth=6, learning_rate=0.04, random_state=42, eval_metric='logloss', n_jobs=-1)
xgb.fit(X_train, y_train)
xgb_pct = pd.Series(xgb.feature_importances_ * 100, index=feature_cols)

# -------------------------------------------------------------
# 5. Plotting: 3 Alag-Alag Subplots
# -------------------------------------------------------------
fig, axes = plt.subplots(1, 3, figsize=(18, 5.5), dpi=300)

models_data = [
    ('OLS Regression (|t-statistic| Share)', ols_pct, '#2b5c8f', axes[0]),
    ('Random Forest (Gini Importance)', rf_pct, '#2ca02c', axes[1]),
    ('XGBoost (Gain Importance)', xgb_pct, '#d95f02', axes[2])
]

for title, series, color, ax in models_data:
    sorted_s = series.sort_values(ascending=True)
    bars = ax.barh(sorted_s.index, sorted_s.values, color=color, edgecolor='black', linewidth=0.8, alpha=0.85)

    # Bar ke aage exact percentage print karein
    for bar in bars:
        w = bar.get_width()
        ax.text(w + 0.8, bar.get_y() + bar.get_height()/2, f'{w:.1f}%',
                va='center', ha='left', fontsize=10, fontweight='bold', color='#222222')

    ax.set_title(title, fontsize=12, fontweight='bold', pad=12)
    ax.set_xlabel('Relative Importance (%)', fontsize=10, fontweight='bold')
    ax.set_xlim(0, max(sorted_s.values) + 12)
    ax.grid(axis='x', linestyle='--', alpha=0.5)
    ax.tick_params(axis='both', which='major', labelsize=10)

plt.suptitle('Individual Feature Preference Across Three Models', fontsize=15, fontweight='bold', y=1.02)
plt.tight_layout()

# Image Save Karein
save_path = '/content/drive/MyDrive/Data/individual_model_feature_preferences.png'
plt.savefig(save_path, bbox_inches='tight', dpi=300)
plt.show()

print(f"Graph successfully saved at: {save_path}")

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import statsmodels.api as sm
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import roc_curve, auc, precision_recall_curve, confusion_matrix
from xgboost import XGBClassifier

# -------------------------------------------------------------------------
# 1. Dataset Load & Split
# -------------------------------------------------------------------------
file_path = '/content/drive/MyDrive/Data/master_landslide_dataset_shuffled.csv'
df = pd.read_csv(file_path).dropna()

features = [
    'DEM_Elevation',
    'DEM_Slope_Deg',
    'DEM_Aspect_Deg',
    'DEM_Curvature',
    'DEM_TWI',
    'IMD_Rainfall_3D'
]

X = df[features]
y = df['Landslide']

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42, stratify=y
)

# -------------------------------------------------------------------------
# 2. Train Models & Predictions
# -------------------------------------------------------------------------
# Random Forest
rf = RandomForestClassifier(n_estimators=200, max_depth=12, random_state=42, n_jobs=-1)
rf.fit(X_train, y_train)
rf_prob = rf.predict_proba(X_test)[:, 1]
rf_pred = rf.predict(X_test)

# XGBoost
xgb = XGBClassifier(n_estimators=250, max_depth=6, learning_rate=0.04, random_state=42, eval_metric='logloss', n_jobs=-1)
xgb.fit(X_train, y_train)
xgb_prob = xgb.predict_proba(X_test)[:, 1]
xgb_pred = xgb.predict(X_test)

# OLS Regression for weights
X_ols = sm.add_constant(df[features])
ols_res = sm.OLS(y, X_ols).fit()
ols_t_vals = ols_res.tvalues.drop('const').abs()
ols_pct = (ols_t_vals / ols_t_vals.sum()) * 100

# -------------------------------------------------------------------------
# PLOT 1: Comparative ROC Curves (RF vs XGBoost)
# -------------------------------------------------------------------------
fpr_rf, tpr_rf, _ = roc_curve(y_test, rf_prob)
fpr_xgb, tpr_xgb, _ = roc_curve(y_test, xgb_prob)

plt.figure(figsize=(7, 6), dpi=300)
plt.plot(fpr_rf, tpr_rf, color='#1f77b4', lw=2.2, label=f'Random Forest (AUC = {auc(fpr_rf, tpr_rf):.4f})')
plt.plot(fpr_xgb, tpr_xgb, color='#d95f02', lw=2.2, label=f'XGBoost (AUC = {auc(fpr_xgb, tpr_xgb):.4f})')
plt.plot([0, 1], [0, 1], color='gray', linestyle='--', lw=1.2)
plt.xlabel('False Positive Rate (1 - Specificity)', fontsize=11, fontweight='bold')
plt.ylabel('True Positive Rate (Sensitivity / Recall)', fontsize=11, fontweight='bold')
plt.title('Receiver Operating Characteristic (ROC) Comparison', fontsize=13, fontweight='bold', pad=12)
plt.legend(loc='lower right', fontsize=10, frameon=True)
plt.grid(True, linestyle=':', alpha=0.6)
plt.tight_layout()
plt.savefig('/content/drive/MyDrive/Data/plot1_roc_comparison.png', dpi=300)
plt.show()

# -------------------------------------------------------------------------
# PLOT 2: Confusion Matrix Heatmaps (Side-by-Side)
# -------------------------------------------------------------------------
fig, axes = plt.subplots(1, 2, figsize=(12, 5), dpi=300)
labels = ['Safe (0)', 'Landslide (1)']

for ax, cm, title, color in zip(
    axes,
    [confusion_matrix(y_test, rf_pred), confusion_matrix(y_test, xgb_pred)],
    ['Random Forest Confusion Matrix', 'XGBoost Confusion Matrix'],
    ['Blues', 'Oranges']
):
    sns.heatmap(cm, annot=True, fmt='d', cmap=color, cbar=False, ax=ax,
                xticklabels=labels, yticklabels=labels, annot_kws={'size': 14, 'weight': 'bold'})
    ax.set_title(title, fontsize=12, fontweight='bold', pad=10)
    ax.set_xlabel('Predicted Label', fontsize=11, fontweight='bold')
    ax.set_ylabel('True Label', fontsize=11, fontweight='bold')

plt.tight_layout()
plt.savefig('/content/drive/MyDrive/Data/plot2_confusion_matrices.png', dpi=300)
plt.show()

# -------------------------------------------------------------------------
# PLOT 3: Precision-Recall Curves
# -------------------------------------------------------------------------
prec_rf, rec_rf, _ = precision_recall_curve(y_test, rf_prob)
prec_xgb, rec_xgb, _ = precision_recall_curve(y_test, xgb_prob)

plt.figure(figsize=(7, 6), dpi=300)
plt.plot(rec_rf, prec_rf, color='#1f77b4', lw=2.2, label=f'Random Forest (AP = {auc(rec_rf, prec_rf):.4f})')
plt.plot(rec_xgb, prec_xgb, color='#d95f02', lw=2.2, label=f'XGBoost (AP = {auc(rec_xgb, prec_xgb):.4f})')
plt.xlabel('Recall (Hazard Catch Rate)', fontsize=11, fontweight='bold')
plt.ylabel('Precision (Positive Predictive Value)', fontsize=11, fontweight='bold')
plt.title('Precision-Recall Curve (Hazard Class: 1)', fontsize=13, fontweight='bold', pad=12)
